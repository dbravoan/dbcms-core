test('the closed preview sends no request; opened it debounces edits, selects children and keeps the last good frame', async ({ page }) => {
    const requests = []; let fail = false;
    page.on('request', request => { if (request.method() === 'POST' && request.url().includes('/blocks/preview')) requests.push(request.postDataJSON()); });
    await page.route('**/blocks/preview', route => fail ? route.fulfill({ status: 503, json: { message: 'Vista temporalmente no disponible' } }) : route.continue());
    await seed(page, [section('root-preview', [{ id: 'first', type: 'heading', text: 'Primer contenido' }, { id: 'second', type: 'heading', text: 'Segundo contenido' }]), section('outside', [{ id: 'outside-heading', type: 'heading', text: 'Otra composición' }])], [0, 'columns', 0, 'blocks', 0]);
    const title = manager(page).locator('[data-block-index="0"]').getByLabel('Texto del título', { exact: true }).first();
    await title.fill('Cambio sin visor');
    await page.waitForTimeout(600);
    expect(requests).toHaveLength(0);
    await expect(manager(page).locator('[data-composition-preview]')).toBeHidden();
    await openPreview(page);
    const frame = page.frameLocator('[data-composition-preview] iframe');
    await expect(frame.getByRole('heading', { name: 'Cambio sin visor', exact: true })).toBeVisible();
    expect(requests.at(-1).payload.id).toBe('root-preview');
    expect(JSON.stringify(requests.at(-1))).not.toContain('Otra composición');
    await closePreview(page);
    const before = requests.length;
    await title.fill('Primer cambio');
    await title.fill('Segundo cambio');
    await title.fill('Cambio agrupado');
    await page.waitForTimeout(600);
    expect(requests.length).toBe(before);
    await openPreview(page);
    await expect(frame.getByRole('heading', { name: 'Cambio agrupado', exact: true })).toBeVisible();
    expect(requests.length).toBe(before + 1);
    await frame.getByRole('heading', { name: 'Segundo contenido', exact: true }).click();
    await expect.poll(() => page.evaluate(() => window.Alpine.$data(document.querySelector('.admin-block-manager')).selectedNode()?.id)).toBe('second');
    const count = requests.length;
    await page.waitForTimeout(600); expect(requests.length).toBe(count);
    await closePreview(page);
    await openDesign(page);
    await manager(page).locator('[data-inspector-design]').getByLabel('Anchura', { exact: true }).fill('1.');
    await openPreview(page);
    await expect(manager(page).getByText('Revisa el valor incompleto. Se conserva la última vista válida.', { exact: true })).toBeVisible();
    await page.waitForTimeout(550); expect(requests.length).toBe(count);
    await expect(frame.getByRole('heading', { name: 'Cambio agrupado', exact: true })).toBeVisible();
    await closePreview(page);
    fail = true;
    await openDesign(page);
    await manager(page).locator('[data-inspector-design]').getByLabel('Anchura', { exact: true }).fill('42');
    await manager(page).locator('[data-inspector-design]').getByLabel('Unidad de Anchura', { exact: true }).selectOption('rem');
    await openPreview(page);
    await expect(manager(page).getByText('Vista temporalmente no disponible', { exact: true })).toBeVisible();
    await expect(frame.getByRole('heading', { name: 'Cambio agrupado', exact: true })).toBeVisible();
    await closePreview(page);
    // A response that arrives after closing never reopens the dialog.
    fail = false;
    await openPreview(page); await closePreview(page);
    await page.waitForTimeout(800);
    await expect(manager(page).locator('[data-composition-preview]')).toBeHidden();
});

