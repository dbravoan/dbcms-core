let labels = EDITOR_LABEL_FALLBACK;

export function setEditorLabels(map) {
    labels = map && typeof map === 'object' && !Array.isArray(map) ? { ...EDITOR_LABEL_FALLBACK, ...map } : EDITOR_LABEL_FALLBACK;
}

export function t(key, replacements = {}) {
    const template = String(labels[key] ?? EDITOR_LABEL_FALLBACK[key] ?? key);
    return template.replace(/:([a-z_]+)/g, (match, name) => (Object.hasOwn(replacements, name) ? String(replacements[name]) : match));
}
